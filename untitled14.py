def reset_game():
    """Volta para a tela inicial."""

    st.session_state.game_started = False
    st.session_state.game_finished = False
    st.session_state.questions = []
    st.session_state.current_question = 0
    st.session_state.score = 0
    st.session_state.correct_answers = 0
    st.session_state.incorrect_answers = 0
    st.session_state.answered = False
    st.session_state.last_answer_correct = False
    st.session_state.last_selected_answer = None


def get_achievement(score):
    """Determina a conquista com base na pontuação."""

    if score >= 36:
        return "🏆 Geometry Champion", (
            "Excelente! Você demonstrou um domínio muito forte "
            "dos conceitos de geometria."
        )

    elif score >= 30:
        return "⭐ Geometry Expert", (
            "Muito bom! Você conhece muito bem as formas, "
            "ângulos e medidas geométricas."
        )

    elif score >= 20:
        return "🎯 Geometry Explorer", (
            "Bom trabalho! Você está desenvolvendo suas "
            "habilidades de geometria."
        )

    else:
        return "💪 Keep Practicing", (
            "Continue praticando! Cada desafio é uma oportunidade "
            "para aprender mais geometria."
        )


def answer_question(selected_answer, question):
    """Verifica a resposta e atualiza a pontuação."""

    if st.session_state.answered:
        return

    st.session_state.answered = True
    st.session_state.last_selected_answer = selected_answer

    if selected_answer == question["answer"]:
        st.session_state.score += 2
        st.session_state.correct_answers += 1
        st.session_state.last_answer_correct = True
    else:
        st.session_state.incorrect_answers += 1
        st.session_state.last_answer_correct = False


