def create_figure():
    """Cria uma figura matplotlib simples para uma pergunta."""
    fig, ax = plt.subplots(figsize=(5, 3.2))

    ax.set_xlim(0, 10)
    ax.set_ylim(0, 7)
    ax.axis("off")

    return fig, ax


def draw_diagram(diagram_type):
    """Desenha o diagrama correspondente à pergunta."""

    fig, ax = create_figure()

    # --------------------------------------------------------
    # TRIÂNGULO
    # --------------------------------------------------------
    if diagram_type == "triangle":
        points = [(2, 1), (5, 6), (8, 1)]
        polygon = Polygon(points, closed=True, fill=False, linewidth=3)
        ax.add_patch(polygon)
        ax.text(5, 0.3, "Triângulo", ha="center", fontsize=14)

    # --------------------------------------------------------
    # QUADRADO
    # --------------------------------------------------------
    elif diagram_type == "square":
        square = Rectangle((3, 1.5), 4, 4, fill=False, linewidth=3)
        ax.add_patch(square)
        ax.text(5, 0.5, "Quadrado", ha="center", fontsize=14)

    # --------------------------------------------------------
    # PENTÁGONO
    # --------------------------------------------------------
    elif diagram_type == "pentagon":
        angles = [90, 18, -54, -126, 162]
        points = []

        for angle in angles:
            rad = math.radians(angle)
            points.append(
                (5 + 2.5 * math.cos(rad),
                 3.5 + 2.5 * math.sin(rad))
            )

        polygon = Polygon(points, closed=True, fill=False, linewidth=3)
        ax.add_patch(polygon)
        ax.text(5, 0.4, "Pentágono", ha="center", fontsize=14)

    # --------------------------------------------------------
    # HEXÁGONO
    # --------------------------------------------------------
    elif diagram_type == "hexagon":
        points = []
        for i in range(6):
            angle = math.radians(60 * i)
            points.append(
                (5 + 2.5 * math.cos(angle),
                 3.5 + 2.5 * math.sin(angle))
            )

        polygon = Polygon(points, closed=True, fill=False, linewidth=3)
        ax.add_patch(polygon)
        ax.text(5, 0.3, "Hexágono", ha="center", fontsize=14)

    # --------------------------------------------------------
    # OCTÓGONO
    # --------------------------------------------------------
    elif diagram_type == "octagon":
        points = []
        for i in range(8):
            angle = math.radians(22.5 + i * 45)
            points.append(
                (5 + 2.4 * math.cos(angle),
                 3.5 + 2.4 * math.sin(angle))
            )

        polygon = Polygon(points, closed=True, fill=False, linewidth=3)
        ax.add_patch(polygon)
        ax.text(5, 0.3, "Octógono", ha="center", fontsize=14)

    # --------------------------------------------------------
    # HEPTÁGONO
    # --------------------------------------------------------
    elif diagram_type == "heptagon":
        points = []
        for i in range(7):
            angle = math.radians(90 + i * (360 / 7))
            points.append(
                (5 + 2.4 * math.cos(angle),
                 3.5 + 2.4 * math.sin(angle))
            )

        polygon = Polygon(points, closed=True, fill=False, linewidth=3)
        ax.add_patch(polygon)
        ax.text(5, 0.3, "Heptágono", ha="center", fontsize=14)

    # --------------------------------------------------------
    # CUBO
    # --------------------------------------------------------
    elif diagram_type == "cube":
        # Frente
        front = Polygon(
            [(2, 1.5), (5.5, 1.5), (5.5, 5), (2, 5)],
            closed=True,
            fill=False,
            linewidth=2.5
        )

        # Trás
        back = Polygon(
            [(4, 3), (7.5, 3), (7.5, 6.5), (4, 6.5)],
            closed=True,
            fill=False,
            linewidth=2.5
        )

        ax.add_patch(front)
        ax.add_patch(back)

        # Ligações
        connections = [
            ((2, 1.5), (4, 3)),
            ((5.5, 1.5), (7.5, 3)),
            ((5.5, 5), (7.5, 6.5)),
            ((2, 5), (4, 6.5))
        ]

        for start, end in connections:
            ax.plot(
                [start[0], end[0]],
                [start[1], end[1]],
                linewidth=2.5
            )

        ax.text(5, 0.4, "Cubo", ha="center", fontsize=14)

    # --------------------------------------------------------
    # PARALELEPÍPEDO
    # --------------------------------------------------------
    elif diagram_type == "cuboid":
        front = Polygon(
            [(1.5, 1.5), (6, 1.5), (6, 4.8), (1.5, 4.8)],
            closed=True,
            fill=False,
            linewidth=2.5
        )

        back = Polygon(
            [(3.5, 3), (8, 3), (8, 6.3), (3.5, 6.3)],
            closed=True,
            fill=False,
            linewidth=2.5
        )

        ax.add_patch(front)
        ax.add_patch(back)

        connections = [
            ((1.5, 1.5), (3.5, 3)),
            ((6, 1.5), (8, 3)),
            ((6, 4.8), (8, 6.3)),
            ((1.5, 4.8), (3.5, 6.3))
        ]

        for start, end in connections:
            ax.plot(
                [start[0], end[0]],
                [start[1], end[1]],
                linewidth=2.5
            )

        ax.text(5, 0.4, "Caixa retangular", ha="center", fontsize=14)

    # --------------------------------------------------------
    # CILINDRO
    # --------------------------------------------------------
    elif diagram_type == "cylinder":
        theta = [i * 2 * math.pi / 100 for i in range(101)]

        x = [5 + 2.2 * math.cos(t) for t in theta]
        y = [5.5 + 0.7 * math.sin(t) for t in theta]

        ax.plot(x, y, linewidth=2.5)

        x2 = [5 + 2.2 * math.cos(t) for t in theta]
        y2 = [2 + 0.7 * math.sin(t) for t in theta]

        ax.plot(x2, y2, linewidth=2.5)

        ax.plot([2.8, 2.8], [2, 5.5], linewidth=2.5)
        ax.plot([7.2, 7.2], [2, 5.5], linewidth=2.5)

        ax.text(5, 0.4, "Cilindro", ha="center", fontsize=14)

    # --------------------------------------------------------
    # CONE
    # --------------------------------------------------------
    elif diagram_type == "cone":
        theta = [i * 2 * math.pi / 100 for i in range(101)]

        x = [5 + 2.4 * math.cos(t) for t in theta]
        y = [1.5 + 0.7 * math.sin(t) for t in theta]

        ax.plot(x, y, linewidth=2.5)

        ax.plot([2.6, 5], [1.5, 6], linewidth=2.5)
        ax.plot([7.4, 5], [1.5, 6], linewidth=2.5)

        ax.scatter([5], [6], s=60)
        ax.text(5, 0.4, "Cone", ha="center", fontsize=14)

    # --------------------------------------------------------
    # ÂNGULO AGUDO
    # --------------------------------------------------------
    elif diagram_type == "acute":
        ax.plot([2, 2], [1.5, 5.5], linewidth=3)
        ax.plot([2, 1.5], [2, 4.5], linewidth=3)

        arc = Arc(
            (2, 2),
            2,
            2,
            angle=0,
            theta1=78,
            theta2=90,
            linewidth=3
        )
        ax.add_patch(arc)

        ax.text(5, 3.5, "< 90°", fontsize=22, fontweight="bold")
        ax.text(5, 0.4, "Ângulo agudo", ha="center", fontsize=14)

    # --------------------------------------------------------
    # ÂNGULO RETO
    # --------------------------------------------------------
    elif diagram_type == "right":
        ax.plot([2, 2], [1.5, 5.5], linewidth=3)
        ax.plot([2, 7], [2, 2], linewidth=3)

        square_mark = Polygon(
            [(2, 2), (2, 3), (3, 3), (3, 2)],
            closed=True,
            fill=False,
            linewidth=2
        )
        ax.add_patch(square_mark)

        ax.text(4.5, 4, "90°", fontsize=22, fontweight="bold")
        ax.text(5, 0.4, "Ângulo reto", ha="center", fontsize=14)

    # --------------------------------------------------------
    # ÂNGULO OBTUSO
    # --------------------------------------------------------
    elif diagram_type == "obtuse":
        ax.plot([2, 8], [2, 2], linewidth=3)
        ax.plot([2, 5], [2, 5.5], linewidth=3)

        arc = Arc(
            (2, 2),
            2.5,
            2.5,
            angle=0,
            theta1=0,
            theta2=55,
            linewidth=3
        )
        ax.add_patch(arc)

        ax.text(5, 4.3, "> 90°", fontsize=22, fontweight="bold")
        ax.text(5, 0.4, "Ângulo obtuso", ha="center", fontsize=14)

    # --------------------------------------------------------
    # RETÂNGULO COM MEDIDAS
    # --------------------------------------------------------
    elif diagram_type == "rectangle_measure":
        rect = Rectangle(
            (2, 2),
            6,
            2.5,
            fill=False,
            linewidth=3
        )
        ax.add_patch(rect)

        ax.text(5, 4.9, "8 m", ha="center", fontsize=16)
        ax.text(8.4, 3.2, "5 m", va="center", fontsize=16)
        ax.text(5, 0.4, "Retângulo", ha="center", fontsize=14)

    # --------------------------------------------------------
    # QUADRADO COM MEDIDA
    # --------------------------------------------------------
    elif diagram_type == "square_measure":
        square = Rectangle(
            (3, 1.5),
            4,
            4,
            fill=False,
            linewidth=3
        )
        ax.add_patch(square)

        ax.text(5, 5.8, "6 m", ha="center", fontsize=16)
        ax.text(7.5, 3.5, "6 m", va="center", fontsize=16)
        ax.text(5, 0.4, "Quadrado", ha="center", fontsize=14)

    # --------------------------------------------------------
    # HORTA
    # --------------------------------------------------------
    elif diagram_type == "garden":
        rect = Rectangle(
            (1.5, 1.5),
            7,
            3.5,
            fill=False,
            linewidth=3
        )
        ax.add_patch(rect)

        ax.text(5, 5.4, "10 m", ha="center", fontsize=16)
        ax.text(8.8, 3.2, "4 m", va="center", fontsize=16)
        ax.text(5, 0.4, "Horta retangular", ha="center", fontsize=14)

    # --------------------------------------------------------
    # CAMPO DE FUTEBOL
    # --------------------------------------------------------
    elif diagram_type == "football":
        field = Rectangle(
            (1.2, 1.3),
            7.6,
            4.2,
            fill=False,
            linewidth=3
        )
        ax.add_patch(field)

        # Linha central
        ax.plot([5, 5], [1.3, 5.5], linewidth=2)

        # Círculo central
        circle = Circle(
            (5, 3.4),
            0.9,
            fill=False,
            linewidth=2
        )
        ax.add_patch(circle)

        ax.text(5, 6, "30 m", ha="center", fontsize=16)
        ax.text(9.1, 3.4, "20 m", va="center", fontsize=16)
        ax.text(5, 0.4, "Campo de futebol", ha="center", fontsize=14)

    # --------------------------------------------------------
    # JANELA
    # --------------------------------------------------------
    elif diagram_type == "window":
        outer = Rectangle(
            (2, 1.3),
            6,
            4,
            fill=False,
            linewidth=3
        )
        ax.add_patch(outer)

        # Divisões da janela
        ax.plot([5, 5], [1.3, 5.3], linewidth=2)
        ax.plot([2, 8], [3.3, 3.3], linewidth=2)

        ax.text(5, 5.7, "3 m", ha="center", fontsize=16)
        ax.text(8.5, 3.3, "2 m", va="center", fontsize=16)
        ax.text(5, 0.4, "Janela retangular", ha="center", fontsize=14)

    # --------------------------------------------------------
    # TELHADO
